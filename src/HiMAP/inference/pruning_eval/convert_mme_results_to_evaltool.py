#!/usr/bin/env python3
import argparse
import json
import os

EVAL_TYPE_DICT = {
    "Perception": ["existence", "count", "position", "color", "posters", "celebrity", "scene", "landmark", "artwork", "OCR"],
    "Cognition": ["commonsense_reasoning", "numerical_calculation", "text_translation", "code_reasoning"],
}

ALL_TASKS = [task for tasks in EVAL_TYPE_DICT.values() for task in tasks]


def sanitize_field(value: str) -> str:
    text = "" if value is None else str(value)
    text = text.replace("\t", " ").replace("\n", " ").strip()
    return text


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--detailed-results", required=True, type=str, help="Path to detailed JSON generated by eval_mme.py")
    parser.add_argument("--output-dir", required=True, type=str, help="Output directory in eval_tool format")
    args = parser.parse_args()

    with open(os.path.expanduser(args.detailed_results), "r", encoding="utf-8") as f:
        items = json.load(f)

    if not isinstance(items, list):
        raise ValueError("Detailed results must be a JSON list.")

    task_to_rows = {task: [] for task in ALL_TASKS}

    for item in items:
        category = sanitize_field(item.get("category", ""))
        if category not in task_to_rows:
            continue

        image_name = sanitize_field(item.get("question_id", ""))
        question = sanitize_field(item.get("question", ""))
        gt = sanitize_field(item.get("gt", "")).lower()
        pred = sanitize_field(item.get("pred", "")).lower()

        row = f"{image_name}\t{question}\t{gt}\t{pred}\n"
        task_to_rows[category].append(row)

    output_dir = os.path.expanduser(args.output_dir)
    os.makedirs(output_dir, exist_ok=True)

    missing_tasks = [task for task, rows in task_to_rows.items() if len(rows) == 0]
    if missing_tasks:
        raise ValueError(
            "Missing task data in detailed results for: " + ", ".join(missing_tasks)
        )

    for task, rows in task_to_rows.items():
        out_path = os.path.join(output_dir, f"{task}.txt")
        with open(out_path, "w", encoding="utf-8") as f:
            f.writelines(rows)

    print(f"Converted detailed results to eval_tool format: {output_dir}")


if __name__ == "__main__":
    main()
